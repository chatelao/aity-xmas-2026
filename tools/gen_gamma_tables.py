#!/usr/bin/env python3
"""Erzeugt die CIE-L*- + Weissabgleich- & Dither-Tabellen fuer C und JavaScript
aus der einzigen Quelle (circuitpython/lib/tannenbaum_layout.py).

Usage:
    python3 tools/gen_gamma_tables.py          # schreibt die Dateien
    python3 tools/gen_gamma_tables.py --check  # Exit 1, falls veraltet (CI)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LAYOUT = ROOT / "circuitpython" / "lib" / "tannenbaum_layout.py"
OUT_H = ROOT / "esp32c6-portal" / "main" / "include" / "gamma_lut.h"
OUT_JS = ROOT / "docs" / "gamma_lut.js"

DITHER_BITS = 3
DITHER_SCALE = 1 << DITHER_BITS  # 8 sub-levels per 8-bit PWM step (8.3 fixed-point)


def cie_lstar_to_linear(level):
    """Identisch zu tannenbaum_layout.cie_lstar_to_linear()."""
    L = level * 100.0
    if L <= 8.0:
        return L / 903.3
    return ((L + 16.0) / 116.0) ** 3


def read_config():
    """Liest WHITE_BALANCE aus tannenbaum_layout.py und baut alle LUTs."""
    src = LAYOUT.read_text(encoding="utf-8")
    m = re.search(r"^WHITE_BALANCE = \((\d+),\s*(\d+),\s*(\d+)\)", src, re.M)
    if not m:
        raise RuntimeError("WHITE_BALANCE not found in tannenbaum_layout.py")
    wb = tuple(int(g) for g in m.groups())

    def lut8(scale):
        return [0] + [
            max(1, min(255, int(cie_lstar_to_linear(i / 255.0) * scale + 0.5)))
            for i in range(1, 256)
        ]

    def lut_fp(scale):
        max_fp = 255 * DITHER_SCALE
        return [0] + [
            max(1, min(max_fp, int(cie_lstar_to_linear(i / 255.0) * scale * DITHER_SCALE + 0.5)))
            for i in range(1, 256)
        ]

    base8 = lut8(255)
    rgb8 = tuple(lut8(c) for c in wb)
    rgb_fp = tuple(lut_fp(c) for c in wb)
    return wb, base8, rgb8, rgb_fp


def rows(lut, indent="    ", per_line=16):
    return ",\n".join(
        indent + ", ".join(str(v) for v in lut[i:i + per_line])
        for i in range(0, len(lut), per_line)
    )


def render(wb, base8, rgb8, rgb_fp):
    lut_r, lut_g, lut_b = rgb8
    fp_r, fp_g, fp_b = rgb_fp
    h = f"""// AUTO-GENERATED by tools/gen_gamma_tables.py - nicht von Hand aendern.
// CIE 1931 L* + Weissabgleich {wb} (WS2812B TypicalLEDStrip),
// identisch zu tannenbaum_layout.py (GAMMA_LUT_R/G/B) plus 8.3-Fixkomma-LUTs fuer 3-Bit-Dithering.
#ifndef GAMMA_LUT_H
#define GAMMA_LUT_H

#include <stdint.h>

#define LED_WB_R {wb[0]}U
#define LED_WB_G {wb[1]}U
#define LED_WB_B {wb[2]}U

#define LED_DITHER_BITS {DITHER_BITS}U
#define LED_DITHER_SCALE {DITHER_SCALE}U

#if defined(__GNUC__) || defined(__clang__)
#define GAMMA_LUT_MAYBE_UNUSED __attribute__((unused))
#else
#define GAMMA_LUT_MAYBE_UNUSED
#endif

// 8-Bit-LUTs (CIE L* + Weissabgleich), byte-identisch zu Python & JS
static const uint8_t GAMMA_LUT_R[256] GAMMA_LUT_MAYBE_UNUSED = {{
{rows(lut_r)}
}};

static const uint8_t GAMMA_LUT_G[256] GAMMA_LUT_MAYBE_UNUSED = {{
{rows(lut_g)}
}};

static const uint8_t GAMMA_LUT_B[256] GAMMA_LUT_MAYBE_UNUSED = {{
{rows(lut_b)}
}};

// 8.3-Fixkomma-LUTs (0..{255 * DITHER_SCALE}) fuer zeitliches 3-Bit-Dithering im C-Portal
static const uint16_t LED_DITHER_LUT_R[256] GAMMA_LUT_MAYBE_UNUSED = {{
{rows(fp_r, per_line=12)}
}};

static const uint16_t LED_DITHER_LUT_G[256] GAMMA_LUT_MAYBE_UNUSED = {{
{rows(fp_g, per_line=12)}
}};

static const uint16_t LED_DITHER_LUT_B[256] GAMMA_LUT_MAYBE_UNUSED = {{
{rows(fp_b, per_line=12)}
}};

#endif  // GAMMA_LUT_H
"""
    js = f"""// AUTO-GENERATED by tools/gen_gamma_tables.py - do not edit by hand.
// CIE 1931 L* + White Balance {list(wb)}, identical to tannenbaum_layout.py.
(function (root) {{
  const CURVE = "cie_lstar";
  const WHITE_BALANCE = [{wb[0]}, {wb[1]}, {wb[2]}];

  // Base CIE L* LUT (neutral white, no WS2812B die attenuation — suitable for sRGB monitors)
  const LUT = new Uint8Array([
{rows(base8, "    ")}
  ]);

  // Per-channel CIE L* + WS2812B white-balance LUTs (identical to firmware)
  const LUT_R = new Uint8Array([
{rows(lut_r, "    ")}
  ]);
  const LUT_G = new Uint8Array([
{rows(lut_g, "    ")}
  ]);
  const LUT_B = new Uint8Array([
{rows(lut_b, "    ")}
  ]);

  // Light actually emitted by the LED (linear) is what the monitor must show; browsers
  // encode with sRGB, so convert linear light -> sRGB for display.
  function ledToDisplay(v) {{
    const lin = v / 255;
    const s = lin <= 0.0031308 ? 12.92 * lin : 1.055 * Math.pow(lin, 1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, s)) * 255);
  }}

  root.XMAS_GAMMA = {{ CURVE, WHITE_BALANCE, LUT, LUT_R, LUT_G, LUT_B, ledToDisplay }};
}})(typeof window !== "undefined" ? window : globalThis);
"""
    return h, js


def main():
    wb, base8, rgb8, rgb_fp = read_config()
    h, js = render(wb, base8, rgb8, rgb_fp)
    if "--check" in sys.argv:
        ok = OUT_H.read_text() == h and OUT_JS.read_text() == js
        print("gamma tables up to date" if ok else "gamma tables OUT OF DATE: run tools/gen_gamma_tables.py")
        sys.exit(0 if ok else 1)
    OUT_H.write_text(h)
    OUT_JS.write_text(js)
    print(f"wrote {OUT_H.relative_to(ROOT)} and {OUT_JS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
